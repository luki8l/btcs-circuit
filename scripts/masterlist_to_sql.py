"""Turn the events masterlist (Excel) into the seed migration.

    python3 scripts/extract_masterlist.py "BTCS_H2_2026_and_2027_EventsMasterlist_NEW.xlsx" /tmp/masterlist.json
    python3 scripts/masterlist_to_sql.py /tmp/masterlist.json supabase/migrations/20261112170100_masterlist.sql

Reads the sheet "INPUT HERE Planning 2027": tier, team ratings, buy-side fit, costs and notes. E-mail addresses and
phone numbers of organisers are removed. Month-only dates ("2nd of the month" placeholders) become date_mode 'month'.
The seed only runs on an empty catalogue (no masterlist events yet), so it is safe to run again.
"""
import json, sys

src, out = sys.argv[1], sys.argv[2]
d = json.load(open(src))

def q(v):
    if v is None: return 'null'
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, (int, float)): return repr(v)
    return "'" + str(v).replace("'", "''") + "'"

def arr(xs, typ):
    return 'array[' + ','.join('null' if x is None else str(int(x)) for x in xs) + ']::' + typ

rows = []
for e in d['events']:
    # ratings outside 1–5 are typos in the sheet (e.g. an audience size in the rating column): drop them
    if e['avg'] is not None and not (1 <= e['avg'] <= 5): e['avg'] = e['sd'] = e['med'] = None
    if e['med'] is not None and not (1 <= e['med'] <= 5): e['med'] = None
    if e['sd'] is not None and not (0 <= e['sd'] <= 4): e['sd'] = None
    mode = e['dm']
    s, en = e['s'], e['e']
    if mode == 'month' and s:
        s = s[:8] + '01'; en = s
    if mode == 'tbd':
        s = en = None
    rows.append('(' + ','.join([
        q(e['n']), q(e['url'] if e['url'] and str(e['url']).startswith('http') else None),
        q(s) + ('::date' if s else ''), q(en) + ('::date' if en else ''), q(mode), q(e['dl']),
        q(e['rg'] or 'TBA'), q(e['c'] or 'TBA'), q(e['l']), q(e['t']), q(e['f']),
        q(e['tier']), q(e['tp']), q(e['avg']), q(e['sd']), q(e['med']), q(e['nr']),
        arr(e['dist'], 'integer[]'), arr(e['fit'], 'smallint[]'),
        q(e['a']), q(e['sz']), q(e['ca']), q(e['cs']), q(e['nt']), q(e['h']), q(e['cm']), q(bool(e['nw'])), "'masterlist'"]) + ')')

sql = ["-- Seed: the 2026/27 external events masterlist (" + str(len(rows)) + " events). Generated by scripts/masterlist_to_sql.py.",
       "-- Runs only while the catalogue has no masterlist events, so it is safe to run again.",
       "do $seed$",
       "begin",
       "  if exists (select 1 from public.events where source = 'masterlist') then return; end if;",
       "  insert into public.events (name, website, start_date, end_date, date_mode, date_note, region, country, city, kind, focus,",
       "    tier, tier_prev, rating_avg, rating_sd, rating_median, rating_n, rating_dist, fit, audience, size, cost_ticket, cost_sponsor,",
       "    notes, history, comment, is_new, source) values",
       ',\n'.join('    ' + r for r in rows) + ';']
for t in d.get('suggestions', []):
    name = 'Private Banking Switzerland Conference and Awards' if 'Private Banking Switzerland' in t else t[:120]
    sql.append(f"  insert into public.suggestions (name, reason, source) values ({q(name)}, {q(t)}, 'masterlist');")
sql += ["end $seed$;", ""]
open(out, 'w').write('\n'.join(sql))
print(len(rows), 'events ->', out)
