create or replace function public.me() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare r text := public.require_role(); p public.profiles;
begin
  select * into p from public.profiles where id = auth.uid();
  return public.person_json(p) || jsonb_build_object('email', p.email);
end $$;

-- everything the app shows, in one call
create or replace function public.bootstrap() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare r text := public.require_role(); staff boolean := r in ('admin', 'events');
begin
  return jsonb_build_object(
    'me', public.me(),
    'today', current_date,
    'people', coalesce((select jsonb_agg(public.person_json(p) order by p.name) from public.profiles p where p.active or staff), '[]'),
    'events', coalesce((select jsonb_agg(public.event_json(e) order by e.start_date nulls last, e.id) from public.events e where not e.archived or staff), '[]'),
    'requests', coalesce((select jsonb_agg(public.request_json(q) order by q.created_at) from public.requests q where q.status <> 'withdrawn'), '[]'),
    'flags', coalesce((select jsonb_agg(jsonb_build_object('eventId', f.event_id, 'note', f.note, 'by', f.flagged_by, 'at', f.created_at)) from public.flags f), '[]'),
    'suggestions', coalesce((select jsonb_agg(jsonb_build_object('id', s.id, 'name', s.name, 'month', s.month, 'city', s.city,
        'website', s.website, 'reason', s.reason, 'source', s.source, 'by', s.suggested_by, 'status', s.status,
        'eventId', s.event_id, 'createdAt', s.created_at) order by s.created_at)
      from public.suggestions s where staff or s.suggested_by = auth.uid()), '[]'));
end $$;

create or replace function public.activity_feed(p_limit integer default 60) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
  perform public.require_role(array['admin', 'events', 'management']);
  return coalesce((select jsonb_agg(x order by x ->> 'at' desc) from (
    select jsonb_build_object('at', a.at, 'actor', a.actor, 'action', a.action, 'eventId', a.event_id, 'requestId', a.request_id, 'details', a.details) x
    from public.activity a order by a.at desc limit least(greatest(coalesce(p_limit, 60), 1), 500)) t), '[]');
end $$;

-- ──────────────────────────────────────── requests ────────────────────────────────────────

create or replace function public.check_request_input(p_mode text, p_ticket text, p_cost numeric, p_groups integer[], p_meetings integer)
returns void language plpgsql immutable set search_path = '' as $$
begin
  if p_mode is null or p_mode not in ('attend', 'speak', 'meetings', 'sponsor') then raise exception 'unknown way of attending' using errcode = '22023'; end if;
  if p_ticket is null or p_ticket not in ('free', 'paid', 'have') then raise exception 'unknown ticket type' using errcode = '22023'; end if;
  if coalesce(p_cost, 0) < 0 or coalesce(p_cost, 0) >= 10000000 then raise exception 'cost out of range' using errcode = '22023'; end if;
  if p_groups is null or cardinality(p_groups) = 0 then raise exception 'pick at least one target group' using errcode = '22023'; end if;
  if exists (select 1 from unnest(p_groups) g where g < 0 or g > 4) then raise exception 'unknown target group' using errcode = '22023'; end if;
  if coalesce(p_meetings, 0) < 0 or coalesce(p_meetings, 0) > 500 then raise exception 'meetings out of range' using errcode = '22023'; end if;
end $$;

-- a sales person (or anyone) asks to go
create or replace function public.request_create(p_event bigint, p_mode text, p_ticket text, p_cost numeric, p_groups integer[], p_meetings integer, p_reason text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare e public.events; q public.requests;
begin
  perform public.require_role();
  select * into e from public.events where id = p_event and not archived;
  if e.id is null then raise exception 'event not found' using errcode = 'P0002'; end if;
  perform public.check_request_input(p_mode, p_ticket, p_cost, p_groups, p_meetings);
  if coalesce(e.tier, 0) >= 4 and length(btrim(coalesce(p_reason, ''))) < 5 then
    raise exception 'Tier % events need a short reason so the events team can make an exception', e.tier using errcode = '22023';
  end if;
  if exists (select 1 from public.requests where event_id = p_event and person_id = auth.uid() and status in ('requested', 'approved')) then
    raise exception 'you already have a request for this event' using errcode = '23505';
  end if;
  insert into public.requests (event_id, person_id, mode, ticket, cost, groups, meetings_planned, reason, created_by)
  values (p_event, auth.uid(), p_mode, p_ticket, case when p_ticket = 'paid' then coalesce(p_cost, 0) else 0 end,
          (select array_agg(distinct g order by g)::smallint[] from unnest(p_groups) g), coalesce(p_meetings, 0), btrim(coalesce(p_reason, '')), auth.uid())
  returning * into q;
  perform public.log('request', p_event, q.id, jsonb_build_object('mode', p_mode, 'ticket', p_ticket));
  return public.request_json(q);
end $$;

-- the owner changes a request that is still waiting
create or replace function public.request_edit(p_id uuid, p_mode text, p_ticket text, p_cost numeric, p_groups integer[], p_meetings integer, p_reason text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare q public.requests; t smallint;
begin
  perform public.require_role();
  select * into q from public.requests where id = p_id for update;
  if q.id is null or q.person_id <> auth.uid() then raise exception 'request not found' using errcode = 'P0002'; end if;
  if q.status <> 'requested' then raise exception 'only waiting requests can be changed' using errcode = '22023'; end if;
  perform public.check_request_input(p_mode, p_ticket, p_cost, p_groups, p_meetings);
  select tier into t from public.events where id = q.event_id;
  if coalesce(t, 0) >= 4 and length(btrim(coalesce(p_reason, ''))) < 5 then raise exception 'Tier 4–5 events need a short reason' using errcode = '22023'; end if;
  update public.requests set mode = p_mode, ticket = p_ticket, cost = case when p_ticket = 'paid' then coalesce(p_cost, 0) else 0 end,
    groups = (select array_agg(distinct g order by g)::smallint[] from unnest(p_groups) g), meetings_planned = coalesce(p_meetings, 0),
    reason = btrim(coalesce(p_reason, '')), updated_at = now()
  where id = p_id returning * into q;
  perform public.log('request_edit', q.event_id, q.id);
  return public.request_json(q);
end $$;

create or replace function public.request_withdraw(p_id uuid) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare q public.requests;
begin
  perform public.require_role();
  select * into q from public.requests where id = p_id for update;
  if q.id is null or q.person_id <> auth.uid() then raise exception 'request not found' using errcode = 'P0002'; end if;
  if q.status not in ('requested', 'approved') then raise exception 'nothing to withdraw' using errcode = '22023'; end if;
  update public.requests set status = 'withdrawn', updated_at = now() where id = p_id returning * into q;
  perform public.log('withdraw', q.event_id, q.id);
  return public.request_json(q);
end $$;

-- the events team decides (one or many at once)
create or replace function public.request_decide(p_ids uuid[], p_status text, p_note text default '') returns integer
language plpgsql security definer set search_path = '' as $$
declare n integer := 0; q public.requests;
begin
  perform public.require_role(array['admin', 'events']);
  if p_status not in ('approved', 'declined') then raise exception 'decide approved or declined' using errcode = '22023'; end if;
  if p_ids is null or cardinality(p_ids) = 0 or cardinality(p_ids) > 200 then raise exception 'pick 1 to 200 requests' using errcode = '22023'; end if;
  for q in select * from public.requests where id = any (p_ids) and status = 'requested' for update loop
    update public.requests set status = p_status, decision_note = left(btrim(coalesce(p_note, '')), 1000), decided_by = auth.uid(),
      decided_at = now(), updated_at = now() where id = q.id;
    perform public.log(p_status, q.event_id, q.id, jsonb_build_object('person', q.person_id, 'note', btrim(coalesce(p_note, ''))));
    n := n + 1;
  end loop;
  return n;
end $$;

-- the events team takes a decision back
create or replace function public.request_reopen(p_id uuid) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare q public.requests;
begin
  perform public.require_role(array['admin', 'events']);
  select * into q from public.requests where id = p_id for update;
  if q.id is null then raise exception 'request not found' using errcode = 'P0002'; end if;
  if q.status not in ('approved', 'declined') then raise exception 'only decided requests can be reopened' using errcode = '22023'; end if;
  if q.status = 'declined' and exists (select 1 from public.requests where event_id = q.event_id and person_id = q.person_id and status in ('requested', 'approved') and id <> q.id) then
    raise exception 'this person already has another request for the event' using errcode = '23505';
  end if;
  update public.requests set status = 'requested', decision_note = '', decided_by = null, decided_at = null, updated_at = now() where id = p_id returning * into q;
  perform public.log('reopen', q.event_id, q.id);
  return public.request_json(q);
end $$;

-- the events team sends someone directly (approved right away)
create or replace function public.request_assign(p_event bigint, p_person uuid, p_mode text, p_note text default '') returns jsonb
language plpgsql security definer set search_path = '' as $$
declare q public.requests;
begin
  perform public.require_role(array['admin', 'events']);
  if not exists (select 1 from public.events where id = p_event and not archived) then raise exception 'event not found' using errcode = 'P0002'; end if;
  if not exists (select 1 from public.profiles where id = p_person and active) then raise exception 'person not found' using errcode = 'P0002'; end if;
  perform public.check_request_input(p_mode, 'free', 0, array[0], 0);
  if exists (select 1 from public.requests where event_id = p_event and person_id = p_person and status in ('requested', 'approved')) then
    raise exception 'this person already has a request for the event' using errcode = '23505';
  end if;
  insert into public.requests (event_id, person_id, status, mode, groups, reason, decision_note, decided_by, decided_at, created_by)
  values (p_event, p_person, 'approved', p_mode, '{}', '', left(btrim(coalesce(p_note, '')), 1000), auth.uid(), now(), auth.uid())
  returning * into q;
  perform public.log('assign', p_event, q.id, jsonb_build_object('person', p_person));
  return public.request_json(q);
end $$;

-- after approval: the event is in HubSpot
create or replace function public.request_hubspot(p_id uuid, p_done boolean) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare q public.requests; r text := public.require_role();
begin
  select * into q from public.requests where id = p_id for update;
  if q.id is null or (q.person_id <> auth.uid() and r not in ('admin', 'events')) then raise exception 'request not found' using errcode = 'P0002'; end if;
  if q.status <> 'approved' then raise exception 'only approved requests' using errcode = '22023'; end if;
  update public.requests set hubspot = coalesce(p_done, false), hubspot_at = case when p_done then now() end, updated_at = now() where id = p_id returning * into q;
  perform public.log(case when p_done then 'hubspot' else 'hubspot_undo' end, q.event_id, q.id);
  return public.request_json(q);
end $$;

-- after the event: leads, meetings, rating, go again
create or replace function public.request_debrief(p_id uuid, p_leads integer, p_held integer, p_rating integer, p_again text, p_note text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare q public.requests; e public.events; r text := public.require_role();
begin
  select * into q from public.requests where id = p_id for update;
  if q.id is null or (q.person_id <> auth.uid() and r not in ('admin', 'events')) then raise exception 'request not found' using errcode = 'P0002'; end if;
  if q.status <> 'approved' then raise exception 'only approved requests can be debriefed' using errcode = '22023'; end if;
  select * into e from public.events where id = q.event_id;
  if e.date_mode = 'tbd' or e.start_date > current_date then raise exception 'the event has not started yet' using errcode = '22023'; end if;
  if p_leads is null or p_leads < 0 or p_leads > 100000 then raise exception 'leads: 0 or more' using errcode = '22023'; end if;
  if p_rating is null or p_rating < 1 or p_rating > 5 then raise exception 'rating: 1 to 5' using errcode = '22023'; end if;
  if p_again is null or p_again not in ('yes', 'maybe', 'no') then raise exception 'go again: yes, maybe or no' using errcode = '22023'; end if;
  if coalesce(p_held, 0) < 0 or coalesce(p_held, 0) > 10000 then raise exception 'meetings: 0 or more' using errcode = '22023'; end if;
  update public.requests set leads = p_leads, meetings_held = coalesce(p_held, 0), rating = p_rating, go_again = p_again,
    debrief_note = left(btrim(coalesce(p_note, '')), 2000), debriefed_at = now(),
    hubspot = true, hubspot_at = coalesce(hubspot_at, now()), updated_at = now()
  where id = p_id returning * into q;
  perform public.log('debrief', q.event_id, q.id, jsonb_build_object('leads', p_leads, 'rating', p_rating));
  return public.request_json(q);
end $$;

