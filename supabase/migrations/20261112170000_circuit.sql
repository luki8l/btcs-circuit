-- Circuit: external events at Bitcoin Suisse. Who goes where, who approved it, what came back.
--
-- Principles (same as the presentation hub)
--   * The database owns the rules: constraints, row level security, functions.
--   * The web app reads and writes only through the functions below. Tables are read-only for signed-in users
--     and invisible to anonymous visitors; every change goes through a function that checks the caller's role
--     and writes the activity log.
--   * Roles: admin (everything, manages accounts) · events (approves, keeps the event catalogue) ·
--     management (sees everything, read-only) · sales (requests, debriefs). Deactivated people can't do anything.
--
-- Run once (Supabase: SQL Editor → paste → Run). Safe to run again.

-- ───────────────────────────────────────── people ─────────────────────────────────────────

create table if not exists public.profiles (
  id         uuid primary key references auth.users (id) on delete cascade,
  email      text not null,
  name       text not null,
  initials   text not null default '',
  role       text not null default 'sales' check (role in ('admin', 'events', 'management', 'sales')),
  market     text not null default '' check (length(market) <= 60),
  team       text not null default '' check (length(team) <= 60),
  title      text not null default '' check (length(title) <= 80),
  active     boolean not null default true,
  created_at timestamptz not null default now()
);
create unique index if not exists profiles_email_key on public.profiles (lower(email));

create or replace function public.name_from_email(e text) returns text
language sql immutable set search_path = '' as $$
  select coalesce(nullif(initcap(regexp_replace(split_part(e, '@', 1), '[._-]+', ' ', 'g')), ''), e)
$$;

create or replace function public.initials_of(n text) returns text
language sql immutable set search_path = '' as $$
  -- first letter of the first and of the last name: "Jan de Vries" → JV
  select upper(coalesce(left(w[1], 1), '') || case when coalesce(array_length(w, 1), 0) > 1 then left(w[array_length(w, 1)], 1) else '' end)
  from (select regexp_split_to_array(nullif(btrim(coalesce(n, '')), ''), '\s+') as w) t
$$;

create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
declare n text := coalesce(nullif(btrim(new.raw_user_meta_data ->> 'name'), ''), public.name_from_email(new.email));
begin
  insert into public.profiles (id, email, name, initials, role, market, team, title)
  values (new.id, new.email, n, public.initials_of(n),
          -- the role only from app metadata, which only the server (secret key) can set; never from what a user signs up with
          case when new.raw_app_meta_data ->> 'role' in ('admin', 'events', 'management', 'sales') then new.raw_app_meta_data ->> 'role' else 'sales' end,
          coalesce(new.raw_user_meta_data ->> 'market', ''), coalesce(new.raw_user_meta_data ->> 'team', ''),
          coalesce(new.raw_user_meta_data ->> 'title', ''))
  on conflict (id) do nothing;
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

-- ───────────────────────────────────────── events ─────────────────────────────────────────

create table if not exists public.events (
  id            bigint generated by default as identity primary key,
  name          text not null check (length(btrim(name)) between 1 and 200),
  website       text check (website is null or length(website) <= 500),
  start_date    date,
  end_date      date,
  date_mode     text not null default 'exact' check (date_mode in ('exact', 'month', 'tbd')),   -- month: only the month is known
  date_note     text check (date_note is null or length(date_note) <= 80),
  region        text not null default 'TBA' check (length(region) <= 20),
  country       text not null default 'TBA' check (length(country) <= 40),
  city          text check (city is null or length(city) <= 120),
  kind          text check (kind is null or length(kind) <= 120),          -- "Type of event" in the masterlist
  focus         text check (focus is null or length(focus) <= 300),
  tier          smallint check (tier between 1 and 5),                     -- 2027 tier; null = not rated yet
  tier_prev     smallint check (tier_prev between 1 and 5),
  rating_avg    numeric(4,2),
  rating_sd     numeric(4,2),
  rating_median numeric(4,2),
  rating_n      integer not null default 0,
  rating_dist   integer[] not null default '{0,0,0,0,0}',                  -- how many colleagues rated 1 … 5
  fit           smallint[] not null default '{null,null,null,null,null}',  -- buy-side fit 1–5 per target group
  audience      text check (audience is null or length(audience) <= 300),
  size          text check (size is null or length(size) <= 12),
  cost_ticket   text check (cost_ticket is null or length(cost_ticket) <= 300),
  cost_sponsor  text check (cost_sponsor is null or length(cost_sponsor) <= 400),
  notes         text check (notes is null or length(notes) <= 4000),
  history       text check (history is null or length(history) <= 1000),  -- "Plan / activity" from the masterlist
  comment       text check (comment is null or length(comment) <= 2000),
  is_new        boolean not null default false,
  source        text not null default 'manual' check (source in ('masterlist', 'suggestion', 'manual')),
  archived      boolean not null default false,
  created_by    uuid references public.profiles (id) on delete set null,
  created_at    timestamptz not null default now(),
  updated_by    uuid references public.profiles (id) on delete set null,
  updated_at    timestamptz not null default now(),
  check (date_mode = 'tbd' or start_date is not null),
  check (end_date is null or start_date is null or end_date >= start_date),
  check (array_length(rating_dist, 1) = 5 and array_length(fit, 1) = 5)
);
create index if not exists events_start_idx on public.events (start_date);

-- ───────────────────────────────────────── requests ───────────────────────────────────────

create table if not exists public.requests (
  id               uuid primary key default gen_random_uuid(),
  event_id         bigint not null references public.events (id) on delete cascade,
  person_id        uuid not null references public.profiles (id) on delete cascade,
  status           text not null default 'requested' check (status in ('requested', 'approved', 'declined', 'withdrawn')),
  mode             text not null default 'attend' check (mode in ('attend', 'speak', 'meetings', 'sponsor')),
  ticket           text not null default 'free' check (ticket in ('free', 'paid', 'have')),
  cost             numeric(12,2) not null default 0 check (cost >= 0 and cost < 10000000),
  groups           smallint[] not null default '{}',                       -- target groups 0–4
  meetings_planned integer not null default 0 check (meetings_planned between 0 and 500),
  reason           text not null default '' check (length(reason) <= 2000),
  decision_note    text not null default '' check (length(decision_note) <= 1000),
  decided_by       uuid references public.profiles (id) on delete set null,
  decided_at       timestamptz,
  hubspot          boolean not null default false,                         -- event created in HubSpot
  hubspot_at       timestamptz,
  leads            integer check (leads between 0 and 100000),
  meetings_held    integer check (meetings_held between 0 and 10000),
  rating           smallint check (rating between 1 and 5),
  go_again         text check (go_again in ('yes', 'maybe', 'no')),
  debrief_note     text not null default '' check (length(debrief_note) <= 2000),
  debriefed_at     timestamptz,
  created_by       uuid references public.profiles (id) on delete set null,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create unique index if not exists requests_one_active on public.requests (event_id, person_id) where status in ('requested', 'approved');
create index if not exists requests_event_idx on public.requests (event_id);
create index if not exists requests_person_idx on public.requests (person_id);

-- events the events team wants covered ("we need someone there")
create table if not exists public.flags (
  event_id   bigint primary key references public.events (id) on delete cascade,
  note       text not null default '' check (length(note) <= 300),
  flagged_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now()
);

-- events someone wants added to the catalogue
create table if not exists public.suggestions (
  id           uuid primary key default gen_random_uuid(),
  name         text not null check (length(btrim(name)) between 1 and 200),
  month        text check (month is null or month ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  city         text not null default '' check (length(city) <= 120),
  website      text not null default '' check (length(website) <= 500),
  reason       text not null default '' check (length(reason) <= 2000),
  source       text not null default 'app' check (source in ('app', 'masterlist')),
  suggested_by uuid references public.profiles (id) on delete set null,
  status       text not null default 'pending' check (status in ('pending', 'added', 'dismissed')),
  event_id     bigint references public.events (id) on delete set null,
  decided_by   uuid references public.profiles (id) on delete set null,
  decided_at   timestamptz,
  created_at   timestamptz not null default now()
);

create table if not exists public.activity (
  id         bigint generated always as identity primary key,
  at         timestamptz not null default now(),
  actor      uuid references public.profiles (id) on delete set null,
  action     text not null,
  event_id   bigint references public.events (id) on delete set null,
  request_id uuid references public.requests (id) on delete set null,
  details    jsonb not null default '{}'
);
create index if not exists activity_at_idx on public.activity (at desc);

