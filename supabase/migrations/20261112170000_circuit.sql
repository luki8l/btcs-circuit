-- the caller's role, or an error if not signed in / deactivated
create or replace function public.require_role(allowed text[] default null) returns text
language plpgsql stable security definer set search_path = '' as $$
declare u uuid := auth.uid(); r text; a boolean;
begin
  if u is null then raise exception 'not signed in' using errcode = '28000'; end if;
  select role, active into r, a from public.profiles where id = u;
  if r is null then raise exception 'not signed in' using errcode = '28000'; end if;
  if not a then raise exception 'your account is deactivated' using errcode = '42501'; end if;
  if allowed is not null and not (r = any (allowed)) then raise exception 'not allowed for your role' using errcode = '42501'; end if;
  return r;
end $$;

-- for row level security: never raises
create or replace function public.my_role() returns text
language sql stable security definer set search_path = '' as $$
  select role from public.profiles where id = auth.uid() and active
$$;

create or replace function public.log(p_action text, p_event bigint default null, p_request uuid default null, p_details jsonb default '{}')
