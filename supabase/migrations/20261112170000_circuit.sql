-- add a suggestion to the catalogue (as an unrated event) or dismiss it
create or replace function public.suggestion_decide(p_id uuid, p_add boolean) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare s public.suggestions; ev bigint;
begin
  perform public.require_role(array['admin', 'events']);
  select * into s from public.suggestions where id = p_id for update;
  if s.id is null then raise exception 'suggestion not found' using errcode = 'P0002'; end if;
  if s.status <> 'pending' then raise exception 'already decided' using errcode = '22023'; end if;
  if p_add then
    insert into public.events (name, website, start_date, end_date, date_mode, city, notes, is_new, source, created_by, updated_by)
    values (s.name, nullif(s.website, ''), case when s.month is not null then (s.month || '-01')::date end, case when s.month is not null then (s.month || '-01')::date end,
            case when s.month is not null then 'month' else 'tbd' end, nullif(s.city, ''), nullif(s.reason, ''), true, 'suggestion', auth.uid(), auth.uid())
    returning id into ev;
  end if;
  update public.suggestions set status = case when p_add then 'added' else 'dismissed' end, event_id = ev, decided_by = auth.uid(), decided_at = now() where id = p_id;
  perform public.log(case when p_add then 'suggestion_added' else 'suggestion_dismissed' end, ev, null, jsonb_build_object('name', s.name));
  return jsonb_build_object('eventId', ev);
end $$;

