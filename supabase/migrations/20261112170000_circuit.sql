create or replace function public.flag_set(p_event bigint, p_on boolean, p_note text default '') returns boolean
language plpgsql security definer set search_path = '' as $$
begin
  perform public.require_role(array['admin', 'events']);
  if not exists (select 1 from public.events where id = p_event) then raise exception 'event not found' using errcode = 'P0002'; end if;
  if p_on then
    insert into public.flags (event_id, note, flagged_by) values (p_event, left(btrim(coalesce(p_note, '')), 300), auth.uid())
    on conflict (event_id) do update set note = excluded.note;
  else
    delete from public.flags where event_id = p_event;
  end if;
  perform public.log(case when p_on then 'flag' else 'unflag' end, p_event);
  return p_on;
end $$;

create or replace function public.suggestion_create(p_name text, p_month text, p_city text, p_website text, p_reason text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare s public.suggestions;
begin
  perform public.require_role();
  insert into public.suggestions (name, month, city, website, reason, suggested_by)
