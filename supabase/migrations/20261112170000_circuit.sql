create or replace function public.people_admin() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
  perform public.require_role(array['admin']);
  return coalesce((select jsonb_agg(public.person_json(p) || jsonb_build_object('email', p.email, 'createdAt', p.created_at,
      'lastSignIn', (select u.last_sign_in_at from auth.users u where u.id = p.id)) order by p.active desc, p.name) from public.profiles p), '[]');
end $$;

create or replace function public.person_save(p_id uuid, p_name text, p_role text, p_market text, p_team text, p_title text, p_active boolean)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare p public.profiles; n text := btrim(coalesce(p_name, ''));
begin
  perform public.require_role(array['admin']);
  if length(n) < 2 or length(n) > 80 then raise exception 'name: 2 to 80 characters' using errcode = '22023'; end if;
  if p_role not in ('admin', 'events', 'management', 'sales') then raise exception 'unknown role' using errcode = '22023'; end if;
  if p_id = auth.uid() and (p_role <> 'admin' or not coalesce(p_active, true)) then
    raise exception 'you cannot remove your own admin access' using errcode = '22023';
  end if;
  update public.profiles set name = n, initials = public.initials_of(n), role = p_role, market = left(btrim(coalesce(p_market, '')), 60),
    team = left(btrim(coalesce(p_team, '')), 60), title = left(btrim(coalesce(p_title, '')), 80), active = coalesce(p_active, true)
  where id = p_id returning * into p;
  if p.id is null then raise exception 'person not found' using errcode = 'P0002'; end if;
  perform public.log('person_save', null, null, jsonb_build_object('person', p.id, 'role', p.role, 'active', p.active));
  return public.person_json(p) || jsonb_build_object('email', p.email);
end $$;

